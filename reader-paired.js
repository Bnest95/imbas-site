export function loopRevealCopy(state, unmatched) {
  const copy = LOOP_STATE_COPY[state] || {};
  if (!unmatched) return copy;
  const next = { ...copy };
  delete next.tag;
  if (LOOP_CONSTRUCT_STATES.includes(state)) next.headline = LOOP_UNMATCHED_HEADLINE;
  return next;
}

