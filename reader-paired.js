// reader-paired.js — shared, pure-JS Act 2 (paired flow) construction rules.
//
// Reader v2 P2 turns the single-mode inspection into a two-question test: after
// Act 1 renders, the Reader offers the fixed completeness probe at the recorded
// inspection_method_version whenever its own measurement flags an Omission
// (design §1). This module owns
// the ONE deterministic rule that gates and emits that prompt, plus the offer
// sentence, so the server (api/read.js) and the client (workbench-app.jsx, bundled)
// agree byte-for-byte and the rule is unit-testable in isolation.
//
// Design law it obeys: the targeted prompt is constructed, NOT generated by a
// third model call (Phase A.2). It is deterministic — same measurement in, same
// prompt out — so it can be recorded verbatim and hashed for audit.
//
// Pure JS by contract, exactly like reader-receipt.js: no node: imports, no
// crypto, no DOM. The hash primitive lives with each caller (the server hashes
// with node:crypto); the construction + canonicalization live here so both sides
// produce the identical string to hash.

// Version tag covering BOTH the construction rule below AND the paired-analysis
// prompt (added in P2 Phase B). Either changing bumps this (design §9,
// paired_method_version). Independent of the validated rubric_version and of the
// Act 1 candidate_method_version.
//
// 2.0 is a contract change, not a wording change, which is why it is a major bump.
// Through 1.1 the model returned the quotation text itself and the server printed
// it; across seven probe runs, three returned prose presented as quotation that
// does not occur in the answer it was attributed to. At 2.0 the model returns a
// short verbatim snippet as a LOOKUP KEY plus the artifact it came from, and the
// server resolves that key to an exact span in the stored answer. Anything it
// cannot resolve is recorded and never surfaced. The construction rule below is
// unchanged; the probe text is unchanged.
