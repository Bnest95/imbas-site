/* Generates compare/frames.data.js from the capture manifest.
 *
 * A file:// page cannot fetch JSON, so the index reads a plain script that defines
 * a global. Same pattern the directions use for the fixture.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { LANE } from "./shoot.mjs";
import { ROWS, DIRECTIONS } from "./matrix.mjs";

const m = JSON.parse(readFileSync(resolve(LANE, "screenshots/MANIFEST.json"), "utf8"));

const frames = {};
for (const f of m.frames) {
  frames[f.name] = { file: "../" + f.file, url: "../" + f.url, h: f.document_height_css_px };
}

const payload = {
  directions: DIRECTIONS,
  rows: ROWS,
  frames: frames,
  renderer: m.capture_spec.renderer,
  parity_mismatches: m.parity.mismatches,
};

writeFileSync(
  resolve(LANE, "compare/frames.data.js"),
  "/* Generated by build/compare.mjs. Labels and file paths only. */\nwindow.IMBAS_FRAMES = " +
    JSON.stringify(payload, null, 1) +
    ";\n",
);

console.log(Object.keys(frames).length, "frames indexed");
